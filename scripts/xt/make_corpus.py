def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", default=str(Path(__file__).parent / "corpus"), help="输出目录"
    )
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    (out / "cross_run_doc.txt").write_text(cross_run_doc(), encoding="utf-8")
    (out / "borderline_doc.txt").write_text(borderline_doc(), encoding="utf-8")
    (out / "noun_flood.txt").write_text(noun_flood_doc(), encoding="utf-8")
    (out / "long_doc_25k.txt").write_text(long_doc_25k(), encoding="utf-8")
    (out / "answer_bomb.json").write_text(
        json.dumps(answer_bomb(), ensure_ascii=False, indent=1), encoding="utf-8"
    )
    for f in sorted(out.iterdir()):
        print(f"wrote {f} ({f.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
